package com.lethio.macros.data.user

import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.google.common.truth.Truth.assertThat
import com.lethio.macros.domain.model.WeightEntry
import java.time.Instant
import java.time.LocalDate
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * A second weigh-in on the same day must correct the day, not vanish.
 *
 * With `@Upsert`, an autogenerated key and a unique index on `measured_on`, Room's insert conflicts
 * on the index and its fallback UPDATE matches `id = 0`: the write succeeds and changes nothing.
 * The defect is in generated Room SQL, so this runs against a real database.
 */
@RunWith(AndroidJUnit4::class)
class WeightDaoTest {

    private lateinit var db: UserDatabase
    private lateinit var repository: WeightRepositoryImpl

    private val today = LocalDate.of(2026, 9, 2)

    @Before
    fun setUp() {
        db =
            Room.inMemoryDatabaseBuilder(
                    InstrumentationRegistry.getInstrumentation().targetContext,
                    UserDatabase::class.java,
                )
                .build()
        repository = WeightRepositoryImpl(db.weightDao())
    }

    @After fun tearDown() = db.close()

    private fun entry(kg: Double) =
        WeightEntry(
            id = WeightEntry.NEW,
            measuredOn = today,
            weightKg = kg,
            createdAt = Instant.EPOCH,
            updatedAt = Instant.EPOCH,
        )

    @Test
    fun aSecondWeighInOnTheSameDayCorrectsItRatherThanBeingDiscarded() = runTest {
        repository.upsert(entry(95.0))
        assertThat(repository.latest()?.weightKg).isEqualTo(95.0)

        // The exact case that was silently lost: a new entry, carrying NEW, for a date that
        // already has a row.
        repository.upsert(entry(78.02))

        assertThat(repository.latest()?.weightKg).isEqualTo(78.02)
    }

    @Test
    fun correctingADayDoesNotAddARow() = runTest {
        repository.upsert(entry(95.0))
        repository.upsert(entry(78.02))

        assertThat(repository.observeEntriesOnce()).hasSize(1)
    }

    @Test
    fun differentDaysStillGetTheirOwnRows() = runTest {
        repository.upsert(entry(95.0))
        repository.upsert(entry(94.0).copy(measuredOn = today.minusDays(1)))

        assertThat(repository.observeEntriesOnce()).hasSize(2)
        // Latest is by date, so yesterday's entry must not displace today's.
        assertThat(repository.latest()?.weightKg).isEqualTo(95.0)
    }

    private suspend fun WeightRepositoryImpl.observeEntriesOnce() = observeEntries().first()
}
